#!/usr/bin/env node
// Generates a G1-dense racing plan for legacy/parent farming runs: picks the best winnable
// race per free turn and spaces entries with an exact DP so the plan never exceeds the
// consecutive-race streak limit, treating the character's mandatory goal races as forced
// entries that consume streak budget. Output is a paste-ready racingPlan block for
// characterPresets.ts plus a summary of what the plan achieves.
//
// Usage:
//   node scripts/generate-racing-plan.mjs --character "Mejiro McQueen" \
//     --aptitudes turf=A,dirt=G,sprint=G,mile=E,medium=A,long=A \
//     [--goals 42,44,56,60,68]   goal turns override / fallback when objectives data lacks them
//     [--min-grade G1]           lowest grade planned (G1 default; G2/G3 widen the pool)
//     [--max-streak 2]           longest allowed run of races on consecutive turns
//     [--min-apt B]              lowest aptitude grade (surface AND distance) considered winnable
//
// Goal turns come from src/data/character_objectives.json (regenerated by the data scraper);
// mandatory races always outrank the plan at runtime, so goal turns are never planned over.
// Reminder: mandatory-plan mode overrides the in-game consecutive-race warning entirely
// (Racing.kt), so this script's spacing is the only guardrail the run gets.
//
// Requires node >= 23.6 (native TypeScript type stripping) for the RaceLab .ts imports below.

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
// Factual race/objective interpretation flows through the landed RaceLab layer (canonical (name,
// turnNumber) identity, hash-verified compiled data, URA objective modeling) instead of re-reading the
// raw JSON here. RaceLab is factual only; all selection/ordering/strategy below stays generator-local.
import { loadRaceCatalog } from "../src/lib/raceLab/catalog.ts"
import { buildObjectiveTimeline, loadRawObjectives } from "../src/lib/raceLab/objectives.ts"
import { APTITUDE_ORDER } from "../src/lib/raceLab/types.ts"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")

function parseArgs(argv) {
    const args = { minGrade: "G1", maxStreak: 2, minApt: "B" }
    for (let i = 2; i < argv.length; i++) {
        switch (argv[i]) {
            case "--character":
                args.character = argv[++i]
                break
            case "--aptitudes":
                args.aptitudes = Object.fromEntries(
                    argv[++i].split(",").map((kv) => {
                        const [k, v] = kv.split("=")
                        return [k.trim().toLowerCase(), v.trim().toUpperCase()]
                    }),
                )
                break
            case "--goals":
                args.goals = argv[++i].split(",").map((t) => parseInt(t.trim(), 10))
                break
            case "--min-grade":
                args.minGrade = argv[++i].toUpperCase()
                break
            case "--max-streak":
                args.maxStreak = parseInt(argv[++i], 10)
                break
            case "--min-apt":
                args.minApt = argv[++i].toUpperCase()
                break
            default:
                fail(`Unknown argument: ${argv[i]}`)
        }
    }
    return args
}

function fail(msg) {
    console.error(`ERROR: ${msg}`)
    process.exit(1)
}

const APT_ORDER = APTITUDE_ORDER
const GRADE_RANK = { G1: 3, G2: 2, G3: 1 }

const args = parseArgs(process.argv)
if (!args.character) fail("--character is required")
if (!args.aptitudes) fail("--aptitudes is required (turf=,dirt=,sprint=,mile=,medium=,long=)")
for (const k of ["turf", "dirt", "sprint", "mile", "medium", "long"]) {
    if (!(k in args.aptitudes)) fail(`--aptitudes is missing '${k}'`)
    if (!APT_ORDER.includes(args.aptitudes[k])) fail(`--aptitudes ${k}=${args.aptitudes[k]} is not a grade`)
}
if (!(args.minGrade in GRADE_RANK)) fail("--min-grade must be G1, G2, or G3")

// Canonical race catalog (hash-verified compiled layer, (name, turnNumber) identity) instead of the raw
// races.json. Same 402 races and the same per-race fields the generator reads (name/date/turnNumber/
// grade/terrain/distanceType/fans); selection/ordering policy below is unchanged.
const catalog = loadRaceCatalog(path.join(root, "src/data/compiled"))
const races = catalog.allRaces()

// Goal turns: RaceLab's URA objective model first, --goals as override/fallback. RaceLab resolves every
// objective option canonically by (raceName, turn) and preserves choice options; the generator keeps its
// own display join and raw-grade G1 test so its summary text is unchanged.
const objectivesPath = path.join(root, "src/data/character_objectives.json")
let goalTurns = null
let goalRaces = []
if (fs.existsSync(objectivesPath)) {
    const rawObjectives = loadRawObjectives(objectivesPath)
    if (args.character in rawObjectives) {
        const timeline = buildObjectiveTimeline(args.character, rawObjectives, catalog)
        goalTurns = timeline.requirements.map((r) => r.turn)
        goalRaces = timeline.requirements.map((r) => ({
            turn: r.turn,
            name: r.options.map((o) => o.raceName).join(" / "),
            g1: r.options.some((o) => o.rawMeta.grade === "G1"),
        }))
    }
}
if (args.goals) {
    if (goalTurns) console.error(`note: --goals overrides the ${goalTurns.length} objective turns on file for ${args.character}`)
    goalTurns = args.goals
    goalRaces = args.goals.map((t) => ({ turn: t, name: "(user-supplied goal)", g1: false }))
}
if (!goalTurns) {
    fail(
        `${args.character} is not in character_objectives.json and no --goals were given. ` +
            "Pass --goals with the character's mandatory race turns - planning blind risks colliding with a goal race.",
    )
}
const goalTurnSet = new Set(goalTurns)

// Candidate pool: one best race per turn - highest grade, then highest fans - that the
// trainee can realistically win (surface AND distance aptitude at or above the bar,
// mirroring the bot's own entry gate which skips anything below B at runtime).
const minAptIdx = APT_ORDER.indexOf(args.minApt)
const aptOf = (race) => ({
    surface: args.aptitudes[race.terrain.toLowerCase()],
    distance: args.aptitudes[race.distanceType.toLowerCase()],
})
const candidates = new Map()
for (const race of races) {
    const rank = GRADE_RANK[race.grade]
    if (!rank || rank < GRADE_RANK[args.minGrade]) continue
    if (goalTurnSet.has(race.turnNumber)) continue
    const apt = aptOf(race)
    if (APT_ORDER.indexOf(apt.surface) < minAptIdx || APT_ORDER.indexOf(apt.distance) < minAptIdx) continue
    const cur = candidates.get(race.turnNumber)
    if (!cur || rank > GRADE_RANK[cur.grade] || (rank === GRADE_RANK[cur.grade] && race.fans > cur.fans)) {
        candidates.set(race.turnNumber, race)
    }
}

// Exact DP over turns: state = current consecutive-race streak. Racing on adjacent turns
// grows the streak; a free turn resets it. Goal turns are forced race transitions - they
// consume streak budget with no skip option, which is exactly the case greedy placement
// gets wrong around goal clusters. Value = (planned G1 count, planned fan sum), lexicographic.
const MAX_TURN = 72
const maxStreak = args.maxStreak
const NEG = { g1: -1, fans: -1, choice: null, prev: null }
const better = (a, b) => (a.g1 !== b.g1 ? a.g1 > b.g1 : a.fans > b.fans)

// dp[streak] for the previous turn; entries carry a backpointer chain for reconstruction.
let dp = Array.from({ length: maxStreak + 1 }, (_, s) => (s === 0 ? { g1: 0, fans: 0, choice: null, prev: null } : NEG))
for (let turn = 1; turn <= MAX_TURN; turn++) {
    const next = Array.from({ length: maxStreak + 1 }, () => NEG)
    const isGoal = goalTurnSet.has(turn)
    const candidate = candidates.get(turn)
    for (let s = 0; s <= maxStreak; s++) {
        const cur = dp[s]
        if (cur.g1 < 0) continue
        if (isGoal) {
            // Forced race. Streak grows past maxStreak only because the game forces it;
            // clamp the state index and let the summary report the true streak.
            const ns = Math.min(s + 1, maxStreak)
            const cand = { g1: cur.g1, fans: cur.fans, choice: { turn, goal: true }, prev: cur }
            if (next[ns].g1 < 0 || better(cand, next[ns])) next[ns] = cand
            continue
        }
        // Option 1: rest/train this turn - streak resets.
        const restCand = { g1: cur.g1, fans: cur.fans, choice: null, prev: cur }
        if (next[0].g1 < 0 || better(restCand, next[0])) next[0] = restCand
        // Option 2: race the turn's best candidate, if the streak allows it.
        if (candidate && s < maxStreak) {
            const cand = {
                g1: cur.g1 + (candidate.grade === "G1" ? 1 : 0),
                fans: cur.fans + candidate.fans,
                choice: { turn, race: candidate },
                prev: cur,
            }
            if (next[s + 1].g1 < 0 || better(cand, next[s + 1])) next[s + 1] = cand
        }
    }
    dp = next
}

let best = NEG
for (const state of dp) if (state.g1 >= 0 && (best.g1 < 0 || better(state, best))) best = state

// Reconstruct.
const planned = []
for (let node = best; node; node = node.prev) {
    if (node.choice && node.choice.race) planned.push(node.choice.race)
}
planned.reverse()

// Summary metrics, including the true max streak with goal turns counted.
const racedTurns = new Set([...planned.map((r) => r.turnNumber), ...goalTurns])
let maxObservedStreak = 0
let run = 0
for (let t = 1; t <= MAX_TURN; t++) {
    run = racedTurns.has(t) ? run + 1 : 0
    if (run > maxObservedStreak) maxObservedStreak = run
}
const plannedG1 = planned.filter((r) => r.grade === "G1").length
const goalG1 = goalRaces.filter((g) => g.g1).length
const fanSum = planned.reduce((a, r) => a + r.fans, 0)

// Warnings.
const warnings = []
const nameCounts = new Map()
for (const r of planned) nameCounts.set(r.name, (nameCounts.get(r.name) ?? 0) + 1)
for (const [name, count] of nameCounts) {
    if (count > 1) {
        warnings.push(
            `"${name}" is planned in both its years - fine for entry (decisions key on the plan's own turnNumber), ` +
                "but the bare-name race map keeps only one year's row, which can mis-window the non-mandatory look-ahead.",
        )
    }
}
for (const r of planned) {
    if (goalTurnSet.has(r.turnNumber - 1) || goalTurnSet.has(r.turnNumber + 1)) {
        warnings.push(`t${r.turnNumber} ${r.name} is adjacent to a goal turn - it extends a forced streak.`)
    }
}

// Output.
console.log(`\n=== ${args.character} - legacy-farming racing plan (URA) ===`)
console.log(`goals on file: ${goalRaces.map((g) => `t${g.turn} ${g.name}`).join(", ") || "none"}`)
console.log(`planned: ${planned.length} races (${plannedG1} G1) | goal G1s: ${goalG1} | projected G1 entries: ${plannedG1 + goalG1}`)
console.log(`plan fan payout: ${fanSum.toLocaleString()} | max consecutive-race streak incl. goals: ${maxObservedStreak}`)
for (const r of planned) {
    const apt = aptOf(r)
    console.log(`  t${String(r.turnNumber).padStart(2)} ${r.grade} ${r.name} (${r.terrain} ${r.distanceType}, ${r.fans.toLocaleString()} fans, apt ${apt.surface}/${apt.distance})`)
}
for (const w of warnings) console.log(`WARNING: ${w}`)
console.log(`\nracingPlan: JSON.stringify([`)
planned.forEach((r, i) => {
    console.log(`    { raceName: ${JSON.stringify(r.name)}, date: ${JSON.stringify(r.date)}, priority: ${i + 1}, turnNumber: ${r.turnNumber} },`)
})
console.log(`]),`)
console.log(`\npair with: enableRacingPlan: true, enableMandatoryRacingPlan: true, ignoreConsecutiveRaceWarning: false`)
console.log(`(mandatory-plan mode overrides the consecutive-race warning at runtime - the spacing above is the only guardrail)`)
